// Turns a validated design into microcontroller code (Arduino C++), using the same discrete
// controller structure the simulator runs: filtered derivative on measurement, clamped output,
// conditional-integration anti-windup.
import { fmtNum } from "./analysis";
import type { ControllerSpec, LabModel } from "./types";

export function suggestSampleTime(wcp: number): number {
  // About 20 samples per crossover period, rounded to a friendly value.
  const ts = wcp > 0 ? (2 * Math.PI) / wcp / 20 : 0.01;
  const nice = [0.0005, 0.001, 0.002, 0.005, 0.01, 0.02, 0.05, 0.1, 0.2, 0.5];
  return nice.reduce((best, v) => (v <= ts ? v : best), nice[0]);
}

const num = (v: number) => (Number.isFinite(v) ? Number(v.toPrecision(6)).toString() : "0");

export function arduinoCode(model: LabModel, spec: ControllerSpec, K: number[], Nbar: number, ts: number): string {
  const header = `// ${model.title}
// Generated by RoboCraft Control Lab. Validated in simulation; tune on hardware with care.
// Input:  ${model.input.name} [${model.input.unit}]   Output: ${model.output.name} [${model.output.unit}]
// Sample time: ${ts * 1000} ms
`;
  if (spec.type === "pid") {
    const useD = spec.kd !== 0;
    return `${header}
const float TS = ${num(ts)};          // s
const float KP = ${num(spec.kp)};
const float KI = ${num(spec.ki)};
const float KD = ${num(spec.kd)};
const float N  = ${num(spec.N)};      // derivative filter, rad/s
const float U_MIN = ${num(model.specs.uMin)}, U_MAX = ${num(model.specs.uMax)};

float setpoint = ${num(model.sim.ref)};
float integ = 0, dfilt = 0;
bool first = true;

float readOutput();                   // TODO: return ${model.output.name} in ${model.output.unit}
void writeInput(float u);             // TODO: apply ${model.input.name} in ${model.input.unit}

float pidStep(float y) {
  float e = setpoint - y;
${useD ? `  if (first) { dfilt = -y / N; first = false; }
  float d = KD * N * (-y - N * dfilt);            // derivative on measurement, filtered
  dfilt = (dfilt + TS * (-y)) / (1 + N * TS);
` : "  float d = 0;\n"}  float u = KP * e + KI * integ + d;
  float uc = constrain(u, U_MIN, U_MAX);
  bool windHigh = u > U_MAX && KI * e > 0, windLow = u < U_MIN && KI * e < 0;
  if (!windHigh && !windLow) integ += e * TS;     // anti-windup
  return uc;
}

void setup() { /* init sensor + driver */ }

void loop() {
  static unsigned long next = micros();
  if ((long)(micros() - next) >= 0) {
    next += (unsigned long)(TS * 1e6);
    writeInput(pidStep(readOutput()));
  }
}
`;
  }
  if (spec.type === "lqr") {
    const states = model.plant.kind === "ss" ? model.plant.stateNames : K.map((_, i) => `x${i + 1}`);
    return `${header}
// Full state feedback from LQR (Q = diag[${spec.Q.map((q) => fmtNum(q)).join(", ")}], R = ${fmtNum(spec.R)})
// States: ${states.join(", ")}
const float TS = ${num(ts)};
const int NX = ${K.length};
const float K[NX] = { ${K.map((k) => num(k)).join(", ")} };
const float NBAR = ${num(Nbar)};
const float U_MIN = ${num(model.specs.uMin)}, U_MAX = ${num(model.specs.uMax)};
float setpoint = ${num(model.sim.ref)};

void readStates(float x[NX]);        // TODO: fill ${states.join(", ")} (use an IMU / encoders / observer)
void writeInput(float u);            // TODO: apply ${model.input.name} in ${model.input.unit}

void setup() { /* init IMU, encoders, motor driver */ }

void loop() {
  static unsigned long next = micros();
  if ((long)(micros() - next) >= 0) {
    next += (unsigned long)(TS * 1e6);
    float x[NX];
    readStates(x);
    float u = NBAR * setpoint;
    for (int i = 0; i < NX; i++) u -= K[i] * x[i];
    writeInput(constrain(u, U_MIN, U_MAX));
  }
}
`;
  }
  return `${header}\n// Open loop: no controller.\n`;
}
