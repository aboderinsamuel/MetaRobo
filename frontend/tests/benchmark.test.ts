// Reproducible benchmark: every ready-made robot (real Muse Spark designs, stored in the repo) runs
// its whole task through the physics simulation, with no API key and no network. `npm test` checks
// the results don't regress; `npm run bench` also writes them to docs/BENCHMARKS.md.
import { readFileSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { sanitizeDesign } from "@/lib/create/design";
import { simulate } from "@/lib/create/sim";

const ROBOTS = [
  { id: "desk-buddy", name: "Desk buddy" },
  { id: "robot-dog", name: "Robot dog" },
  { id: "laundry-humanoid", name: "Laundry humanoid" },
  { id: "water-carrier", name: "Water carrier" },
];

describe("benchmark: the ready-made robots in full physics", () => {
  it(
    "runs every task and reports steps, grasps, clearance and speed",
    async () => {
      const rows: { name: string; joints: number; parts: number; steps: string; ok: number; total: number; simS: number; wallMs: number; grasps: string; notes: string }[] = [];
      for (const r of ROBOTS) {
        const d = sanitizeDesign(JSON.parse(readFileSync(`public/examples/${r.id}.json`, "utf8")));
        const t0 = performance.now();
        const rec = await simulate(d);
        const wallMs = performance.now() - t0;
        const ok = rec.steps.filter((s) => s.ok).length;
        const grasps = d.task.filter((s) => s.action === "grasp").length;
        const missed = rec.checks.filter((c) => c.title.startsWith("Missed")).length;
        const notes = rec.checks.filter((c) => c.level === "error").map((c) => c.title);
        rows.push({
          name: r.name,
          joints: d.robot.nodes.filter((n) => n.joint.type !== "fixed").length,
          parts: d.robot.nodes.length,
          steps: `${ok} / ${rec.steps.length}`,
          ok,
          total: rec.steps.length,
          simS: rec.duration,
          wallMs,
          grasps: grasps ? `${grasps - Math.min(missed, grasps)} / ${grasps}` : "n/a",
          notes: notes.length ? [...new Set(notes)].slice(0, 2).join("; ") : "",
        });
      }

      // Regression floor: today's results. A change that breaks a robot's task fails the suite.
      const floor: Record<string, number> = { "Desk buddy": 14, "Robot dog": 12, "Laundry humanoid": 37, "Water carrier": 8 };
      for (const row of rows) expect(row.ok, row.name).toBeGreaterThanOrEqual(floor[row.name]);

      // `npm run bench` writes the table; plain `npm test` only checks it.
      if (process.env.npm_lifecycle_event === "bench") {
        const okAll = rows.reduce((s, r) => s + r.ok, 0),
          totalAll = rows.reduce((s, r) => s + r.total, 0);
        const md = [
          "# Benchmarks",
          "",
          "Generated by `npm run bench` (in `frontend/`): every ready-made robot runs its whole task through the physics simulation (Rapier rigid bodies and cloth, IK motion planning, contact-based grasping, outcome checks). No API key, no network; the designs are real Muse Spark outputs stored in `public/examples/`.",
          "",
          `**${okAll} of ${totalAll} task steps succeed (${Math.round((okAll / totalAll) * 100)}%) across ${rows.length} robots.**`,
          "",
          "| Robot | Joints | Parts | Task steps succeeded | Grasps that held (real contact) | Simulated time | Wall-clock to simulate | Failing checks |",
          "|---|---:|---:|---:|---:|---:|---:|---|",
          ...rows.map((r) => `| ${r.name} | ${r.joints} | ${r.parts} | ${r.steps} | ${r.grasps} | ${r.simS.toFixed(1)} s | ${(r.wallMs / 1000).toFixed(1)} s | ${r.notes || "none"} |`),
          "",
          "Wall-clock time depends on the machine; the step and grasp results are deterministic.",
          "",
        ].join("\n");
        writeFileSync("../docs/BENCHMARKS.md", md);
      }
    },
    600_000,
  );
});
